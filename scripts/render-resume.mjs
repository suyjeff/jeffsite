// Renders the resumé PDF into what the in-page viewer (components/resume) shows:
//   public/resume/page.svg             the page as vector art, crisp at any zoom or tilt
//   components/resume/resumeText.ts    every line of text with its position, for the invisible
//                                      selectable layer laid over the art (copy, find, screen readers)
// Needs poppler (pdftocairo, pdftotext). Run after replacing the PDF:
//   node scripts/render-resume.mjs public/SuJeffResume_oct2025.pdf
import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const pdf = process.argv[2]
if (!pdf) {
  console.error('usage: node scripts/render-resume.mjs <path to resume pdf in public/>')
  process.exit(1)
}

mkdirSync('public/resume', { recursive: true })

// Vector art. Cairo writes six decimals; two are plenty at 612pt wide and halve the file.
const svg = execFileSync('pdftocairo', ['-svg', pdf, '-'], { encoding: 'utf8', maxBuffer: 64 << 20 })
const slim = svg
  .replace(/-?\d+\.\d{3,}/g, (n) => String(Math.round(parseFloat(n) * 100) / 100))
  .replace(/\n\s*/g, '\n')
writeFileSync('public/resume/page.svg', slim)

// Text with boxes, in reading order.
const layout = execFileSync('pdftotext', ['-bbox-layout', '-f', '1', '-l', '1', pdf, '-'], { encoding: 'utf8' })
const [, pw, ph] = layout.match(/<page width="([\d.]+)" height="([\d.]+)"/)
const width = parseFloat(pw)
const height = parseFloat(ph)
const decode = (s) =>
  s.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'")
const r = (n) => Math.round(n * 10) / 10

const lines = []
for (const [, body] of layout.matchAll(/<line [^>]*>([\s\S]*?)<\/line>/g)) {
  const words = [...body.matchAll(/<word xMin="([\d.]+)" yMin="([\d.]+)" xMax="([\d.]+)" yMax="([\d.]+)">([^<]*)<\/word>/g)]
    .map(([, x0, y0, x1, y1, t]) => ({ x0: +x0, y0: +y0, x1: +x1, y1: +y1, t: decode(t) }))
    // Pages draws some dashes as loose glyphs that poppler parks at the page's bottom edge.
    .filter((w) => w.y0 < height - 1)
  if (!words.length) continue
  const size = Math.max(...words.map((w) => w.y1 - w.y0))
  // Those missing dashes leave a wide gap between words ("June 2021   August 2021"): put them back.
  let text = words[0].t
  for (let i = 1; i < words.length; i++) {
    const gap = words[i].x0 - words[i - 1].x1
    const range = /\d{4}$/.test(words[i - 1].t) && /^(\d{4}|Present|[A-Z][a-z]+)$/.test(words[i].t)
    text += range && gap > size * 0.3 ? ' – ' : ' '
    text += words[i].t
  }
  const x0 = Math.min(...words.map((w) => w.x0))
  const x1 = Math.max(...words.map((w) => w.x1))
  const y1 = Math.max(...words.map((w) => w.y1))
  const href = /^\S+@\S+\.\w+$/.test(text) ? `mailto:${text}` : /^[\w-]+\.(com|org|net|io|dev|me)$/.test(text) ? `https://${text}` : undefined
  lines.push({ x: r(x0), y: r(y1 - size * 0.22), w: r(x1 - x0), size: r(size * 0.8), text, ...(href && { href }) })
}

// Content order follows how Pages drew the page, not how it reads: put it in column order, drop the lone
// bullet glyphs (the art shows them), and join fragments that share a baseline. A date range is split around a
// dash glyph poppler can't place, so that join gets the dash back.
// The right column starts well left of centre; anything past 40% of the width belongs to it.
const half = width * 0.4
const ordered = lines
  .filter((l) => l.text !== '•')
  .map((l) => ({ ...l, text: l.text.replace(/^• /, '') }))
  .sort((a, b) => (a.x >= half) - (b.x >= half) || a.y - b.y || a.x - b.x)
const merged = []
for (const l of ordered) {
  const prev = merged[merged.length - 1]
  if (prev && Math.abs(prev.y - l.y) < 1 && (prev.x >= half) === (l.x >= half)) {
    prev.text += /\d$/.test(prev.text) ? ' – ' + l.text : ' ' + l.text
    prev.w = r(l.x + l.w - prev.x)
  } else merged.push({ ...l })
}

const src = `// Generated by scripts/render-resume.mjs from ${path.basename(pdf)}. Do not edit by hand.
export type ResumeLine = { x: number; y: number; w: number; size: number; text: string; href?: string }

export const resumePdf = '/${path.relative('public', pdf)}'
export const resumeArt = '/resume/page.svg'
export const resumeSize = { width: ${width}, height: ${height} }
export const resumeLines: ResumeLine[] = ${JSON.stringify(merged, null, 2)}
`
writeFileSync('components/resume/resumeText.ts', src)
console.log(`page.svg ${(slim.length / 1024).toFixed(0)} KB, ${merged.length} lines`)
